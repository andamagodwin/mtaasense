// Writes the website's copies of the palette in theme/colors.js. Files are only rewritten when their content
// changes, so running this on every dev start or build doesn't trigger reloads.
//
//   frontend/src/app/theme.css   Tailwind theme variables (`bg-accent`, `var(--color-ink)`, ...)
//   frontend/src/lib/colors.ts   hex values for code that can't read CSS variables (MapLibre paint, metadata)
//   frontend/public/icon.svg     the favicon's tile and monogram fills
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { colors } = createRequire(import.meta.url)("./colors.js");
const HEADER = "Generated by theme/sync.mjs from theme/colors.js. Edit that file, not this one.";

function write(path, content) {
  const file = join(root, path);
  let current = null;
  try {
    current = readFileSync(file, "utf8");
  } catch {}
  if (current === content) return;
  writeFileSync(file, content);
  console.log(`theme: wrote ${relative(root, file)}`);
}

// `accent: { DEFAULT, hover }` becomes --color-accent and --color-accent-hover, as Tailwind names them.
const variables = Object.entries(colors).flatMap(([name, value]) =>
  typeof value === "string"
    ? [[name, value]]
    : Object.entries(value).map(([shade, hex]) => [shade === "DEFAULT" ? name : `${name}-${shade}`, hex]),
);

const ink = [1, 3, 5].map((i) => parseInt(colors.ink.DEFAULT.slice(i, i + 2), 16)).join(" ");

write(
  "frontend/src/app/theme.css",
  `/* ${HEADER} */
@theme {
${variables.map(([name, hex]) => `  --color-${name}: ${hex};`).join("\n")}

  /* Shadows are tinted with the ink colour. */
  --shadow-card: 0 1px 2px rgb(${ink} / 0.04), 0 1px 1px rgb(${ink} / 0.03);
  --shadow-pop: 0 12px 32px -12px rgb(${ink} / 0.22), 0 2px 6px rgb(${ink} / 0.06);
  /* Review dashboard cards: a soft lift, with a hairline ring in place of the border. */
  --shadow-panel: rgba(0, 0, 0, 0.05) 0px 6px 24px 0px, rgba(0, 0, 0, 0.08) 0px 0px 0px 1px;
}
`,
);

write(
  "frontend/src/lib/colors.ts",
  `// ${HEADER}
export const colors = ${JSON.stringify(colors, null, 2)} as const;
`,
);

const icon = readFileSync(join(root, "frontend/public/icon.svg"), "utf8");
write(
  "frontend/public/icon.svg",
  icon
    .replace(/(<rect\b[^>]*\bfill=")[^"]*"/, `$1${colors.accent.DEFAULT}"`)
    .replace(/(<path\b[^>]*\bfill=")[^"]*"/, `$1${colors.paper}"`),
);
